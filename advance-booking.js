  // จัดการวันปฏิทินด้วย UTC เพื่อไม่ให้วันคลาดเคลื่อนตามเขตเวลาของเครื่อง
  function parseDate(iso) {
    if (typeof iso !== 'string' || !/^\d{4}-\d{2}-\d{2}$/.test(iso)) return null;
    const date = new Date(iso + 'T12:00:00Z');
    return Number.isFinite(date.getTime()) && date.toISOString().slice(0, 10) === iso ? date : null;
  }

  function shiftDate(iso, days) {
    const date = parseDate(iso);
    date.setUTCDate(date.getUTCDate() + days);
    return date.toISOString().slice(0, 10);
  }

  function bangkokToday(now) {
    const parts = new Intl.DateTimeFormat('en-CA', {
      timeZone: TIME_ZONE, year: 'numeric', month: '2-digit', day: '2-digit'
    }).formatToParts(now);
    const part = key => parts.find(item => item.type === key).value;
    return `${part('year')}-${part('month')}-${part('day')}`;
  }

  function formatDate(iso) {
    return new Intl.DateTimeFormat('th-TH', {
      timeZone: TIME_ZONE, year: 'numeric', month: 'long', day: 'numeric'
    }).format(parseDate(iso));
  }

