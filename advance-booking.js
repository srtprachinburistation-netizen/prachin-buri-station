  function statusForOpenDate(iso, time, now) {
    if (!time) return {kind: 'info', text: 'ตรวจเวลาเปิดขาย'};
    const opensAt = new Date(`${iso}T${time}:00+07:00`);
    if (now >= opensAt) {
      return {kind: 'open', text: 'เปิดจองแล้ว', detail: 'สามารถตรวจสอบที่นั่งใน D-Ticket ได้'};
    }
    const days = Math.round((parseDate(iso) - parseDate(bangkokToday(now))) / DAY_MS);
    if (days === 0) return {kind: 'waiting', text: `เปิดวันนี้ ${time} น.`, detail: 'ยังไม่ถึงเวลาเปิดจอง'};
    if (days === 1) return {kind: 'waiting', text: `เปิดพรุ่งนี้ ${time} น.`, detail: 'เตรียมทำรายการล่วงหน้าได้'};
    return {
      kind: 'waiting', text: `อีกประมาณ ${days} วัน`,
      detail: `เริ่มเปิด ${formatDate(iso)} เวลา ${time} น.`
    };
  }

  function calculateBooking(input = {}, now = new Date()) {
    const error = message => ({ok: false, error: message});
    if (!input || typeof input !== 'object') return error('กรุณาระบุข้อมูลการเดินทาง');
    if (!(now instanceof Date) || !Number.isFinite(now.getTime())) return error('เวลาปัจจุบันไม่ถูกต้อง');
    const travelDate = input.travelDate;
    if (!parseDate(travelDate)) return error('กรุณาระบุวันเดินทางเป็น ค.ศ. รูปแบบ YYYY-MM-DD');
    if (travelDate < bangkokToday(now)) return error('วันที่เดินทางผ่านไปแล้ว กรุณาเลือกวันนี้หรือวันในอนาคต');

    const mode = input.mode || (input.line ? 'station' : 'manual');
    if (!['manual', 'station'].includes(mode)) return error('โหมดต้องเป็น manual หรือ station');
    const line = mode === 'station' ? input.line || '' : '';
    let train = null, total, passenger, p1, p2;
    let reservationType = input.reservationType;
    let origin = 'กรอกระยะทางเอง', destination = 'กรอกระยะทางเอง';
    let trainOrigin, trainDest;

    if (mode === 'station') {
      if (!Object.prototype.hasOwnProperty.call(trainData, line)) return error('กรุณาเลือกสายทางจาก trainData');
      if (input.trainId) {
        train = getTrain(line, input.trainId);
        if (!train) return error('ไม่พบรหัสขบวนรถในสายทางที่เลือก');
      }
      origin = String(input.origin || '').trim();
      destination = String(input.destination || '').trim();
      if (!origin || !destination) return error('กรุณาเลือกสถานีขึ้นและสถานีลง');
      if (!exactStation(line, origin) || !exactStation(line, destination)) {
        return error('กรุณาเลือกสถานีขึ้นและสถานีลงจากข้อมูลสถานี');
      }
      if (train) {
        const stops = activeStationNames(line, train);
        if (!stops.includes(origin) || !stops.includes(destination)) {
          return error('สถานีที่เลือกไม่อยู่ในรายการจอดของขบวนรถนี้');
        }
        reservationType = getReservationType(train);
      }
      trainOrigin = train ? train.origin : String(input.trainOrigin || '').trim();
      trainDest = train ? train.dest : String(input.trainDest || '').trim();
      p1 = getKm(line, origin);
      p2 = getKm(line, destination);
      const t1 = getKm(line, trainOrigin), t2 = getKm(line, trainDest);
      total = [t1, t2].every(Number.isFinite) ? Math.abs(t2 - t1) : NaN;
      passenger = Math.abs(p2 - p1);
    } else {
      // รับตัวเลขหรือข้อความจากช่องกรอก แต่ไม่รับข้อความที่มีหน่วยปนมา
      const number = value => typeof value === 'number' ? value :
        typeof value === 'string' && value.trim() ? Number(value) : NaN;
      total = number(input.totalDistance);
      passenger = number(input.passengerDistance);
    }

    if (!['reserved', 'nonreserved'].includes(reservationType)) {
      return error('กรุณาเลือก reservationType เป็น reserved หรือ nonreserved');
    }
    const base = {
      ok: true, travelDate, origin, destination, line,
      trainId: train ? train.id : '', trainName: train ? train.name : '',
      total: Number.isFinite(total) ? total : null,
       passenger: Number.isFinite(passenger) ? passenger : null,
       kmReference: mode==='station' ? trainOrigin : '',
       originKmFromTrain: mode==='station' ? getKmFromTrainOrigin(line,origin,trainOrigin) : null,
       destinationKmFromTrain: mode==='station' ? getKmFromTrainOrigin(line,destination,trainOrigin) : null
    };

    // ขบวนไม่สำรองที่นั่งไม่ใช้เกณฑ์ระยะทาง ตามลำดับตรวจในต้นฉบับ
    if (reservationType === 'nonreserved') {
      return {
        ...base, type: 'nonreserved', days: 0,
        bookingDate: null, saleDate: travelDate, openTime: null,
        headline: 'ซื้อในวันเดินทาง', summary: BOOKING_RULES.nonReservedText
      };
    }
    if (mode === 'station' && !train) {
      if (!trainOrigin || !trainDest) return error('กรุณาระบุต้นทางและปลายทางของขบวนรถ');
      if (!exactStation(line, trainOrigin) || !exactStation(line, trainDest)) {
        return error('ต้นทางและปลายทางของขบวนต้องเลือกจากข้อมูลสถานี');
      }
    }
    if (!Number.isFinite(total) || !Number.isFinite(passenger)) return error('กรุณาระบุข้อมูลระยะทางให้ครบ');
    if (mode === 'station') {
      const t1 = getKm(line, trainOrigin), t2 = getKm(line, trainDest);
      const min = Math.min(t1, t2), max = Math.max(t1, t2);
      if (p1 < min || p1 > max || p2 < min || p2 > max) {
        return error('สถานีขึ้นและสถานีลงต้องอยู่ภายในช่วงต้นทางและปลายทางของขบวนรถ');
      }
    }
    if (total <= 0 || passenger <= 0) return error('ระยะทางต้องมากกว่า 0 และต้นทางกับปลายทางต้องไม่เป็นสถานีเดียวกัน');
    if (passenger > total) return error('ระยะทางผู้โดยสารต้องไม่เกินระยะทางวิ่งทั้งหมดของขบวน');

    const percentage = (passenger / total) * 100;
    let type = 'standard';
    let days = bookingDaysFromPercentage(percentage);
    let openTime = BOOKING_RULES.standardOpenTime;
    let trainNo, note = '';

    if (mode === 'station' && train && BOOKING_RULES.special887888.ids.includes(train.id)) {
      const rule = classify887888(p1, p2);
      if (rule === 'special-48h') {
        type = rule;
        days = 2;
        trainNo = p2 > p1 ? '887' : '888';
        const terminal = BOOKING_RULES.special887888.terminalTimes[trainNo];
        openTime = terminal && origin === terminal.station ? terminal.time : null;
        note = 'ภายใน 48 ชั่วโมงก่อนรถออกจากสถานีขึ้น ต้องตรวจเวลาออกของสถานีขึ้นให้ตรง';
      } else if (rule === 'special-1day') {
        type = rule;
        days = 1;
        note = 'เงื่อนไขนี้อ้างอิงผลทดสอบ D-Ticket ที่บันทึกไว้ในต้นฉบับ โปรดตรวจ D-Ticket อีกครั้ง';
      } else {
        note = 'ขบวน 887/888 ช่วงฝั่งกรุงเทพไปตั้งแต่ชลบุรีขึ้นไป ใช้เกณฑ์ระยะทาง 1 / 30 / 90 วัน';
      }
    }

    const bookingDate = shiftDate(travelDate, -days);
    const result = {
      ...base, type, percentage, days, bookingDate, openTime,
      headline: type === 'special-48h' ? `ขบวน ${trainNo} • ภายใน 48 ชั่วโมง` : `จองล่วงหน้า ${days} วัน`,
      summary: openTime ? `เริ่มจอง ${formatDate(bookingDate)} เวลา ${openTime} น.` :
        `${formatDate(bookingDate)} ณ เวลาเดียวกับเวลาขบวนออกจากสถานี ${origin}`,
      status: statusForOpenDate(bookingDate, openTime, now), note
    };
    if (type === 'special-48h') {
      result.trainNo = trainNo;
      result.saleDate = bookingDate;
      result.requiresDepartureTime = openTime === null;
      if (![0, 6].includes(parseDate(travelDate).getUTCDay())) {
        result.warning = 'วันเดินทางไม่ใช่เสาร์หรืออาทิตย์ตามตารางอ้างอิงในต้นฉบับ โปรดตรวจตารางเดินรถอีกครั้ง';
      }
    }
    return result;
  }

